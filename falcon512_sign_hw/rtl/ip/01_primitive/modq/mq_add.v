`timescale 1ns/1ps
/*
 * mq_add.v
 *
 * Addition modulo q = 12289.
 *
 * d = (a + b) mod q
 *
 * Inputs a, b must be in range 0 <= a, b < q.
 */

module mq_add (
    a,
    b,
    d
);

//---------------------------------------------------------------------
//   Parameter
//---------------------------------------------------------------------
localparam Q_WIDTH = 14;
localparam Q       = 14'd12289;

//---------------------------------------------------------------------
//   Input & Output
//---------------------------------------------------------------------
input  [Q_WIDTH-1:0] a;
input  [Q_WIDTH-1:0] b;

output [Q_WIDTH-1:0] d;

//---------------------------------------------------------------------
//   Wire
//---------------------------------------------------------------------
wire [Q_WIDTH:0] sum;
wire [Q_WIDTH:0] sum_sub_q;

//---------------------------------------------------------------------
//   Combinational Logic
//---------------------------------------------------------------------
assign sum       = {1'b0, a} + {1'b0, b};
assign sum_sub_q = sum - {1'b0, Q};

assign d = (sum >= Q) ? sum_sub_q[Q_WIDTH-1:0]
                      : sum[Q_WIDTH-1:0];

endmodule
