`timescale 1ns/1ps
/*
 * mq_sub.v
 *
 * Subtraction modulo q = 12289.
 *
 * d = (a - b) mod q
 *
 * Inputs a, b must be in range 0 <= a, b < q.
 */

module mq_sub (
    a,
    b,
    d
);

//---------------------------------------------------------------------
//   Parameter
//---------------------------------------------------------------------
localparam Q_WIDTH = 14;
localparam Q       = 14'd12289;

//---------------------------------------------------------------------
//   Input & Output
//---------------------------------------------------------------------
input  [Q_WIDTH-1:0] a;
input  [Q_WIDTH-1:0] b;

output [Q_WIDTH-1:0] d;

//---------------------------------------------------------------------
//   Wire
//---------------------------------------------------------------------
wire [Q_WIDTH:0] sub;
wire [Q_WIDTH:0] sub_add_q;

//---------------------------------------------------------------------
//   Combinational Logic
//---------------------------------------------------------------------
assign sub       = {1'b0, a} - {1'b0, b};
assign sub_add_q = sub + {1'b0, Q};

assign d = (sub[Q_WIDTH]) ? sub_add_q[Q_WIDTH-1:0]
                          : sub[Q_WIDTH-1:0];

endmodule
